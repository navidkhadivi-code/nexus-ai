export function t(key: keyof typeof dict | string, lang: Lang): string {
  const e = dict[key];
  return e ? e[lang] : String(key);
}

export function fmt(n: number | null | undefined, digits = 2, lang: Lang = 'en'): string {
  if (n == null || !isFinite(n)) return '—';
  const loc = lang === 'fa' ? 'fa-IR' : 'en-US';
  try { return new Intl.NumberFormat(loc, { maximumFractionDigits: digits, minimumFractionDigits: Math.min(digits, 2) }).format(n); }
  catch { return n.toFixed(digits); }
}
